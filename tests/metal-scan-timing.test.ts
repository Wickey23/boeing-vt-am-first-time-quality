import {test} from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {slicePhysicalStl} from "../lib/lpbf-physical-slicer";
import {parsePhysicalScanCsv} from "../lib/lpbf-physical-schedule";
import {registerPhysicalScanToSlices} from "../lib/lpbf-slice-registration";
import {calculatePhysicalScanTiming} from "../lib/metal-scan-timing";
const f=async(name:string)=>{const b=await readFile("public/verification/"+name);return b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength) as ArrayBuffer;};
const sha=(b:ArrayBuffer)=>createHash("sha256").update(Buffer.from(b)).digest("hex");
test("supplied 50-layer cube file reports real commanded duration and laser states, not claimed actual print time",async()=>{
 const stl=await f("cube-10mm.stl"),raw=await f("cube-10mm-physical-scan.csv");
 const slices=await slicePhysicalStl(stl,{unitScaleToMm:1,xyPitchMm:1,layerThicknessMm:.2});
 const scan=parsePhysicalScanCsv(new TextDecoder().decode(raw));
 const registration=registerPhysicalScanToSlices({slices,scan,scanSourceSha256:sha(raw)});
 const unknown={outsideCsvConfirmed:false,recoatSecondsPerLayer:8,preparationMinutes:10,cooldownMinutes:15};
 const r=calculatePhysicalScanTiming(scan,slices,registration,unknown);
 assert.ok(Math.abs(r.elapsedCommandSeconds-.5)<1e-9);
 assert.ok(Math.abs(r.laserOnSeconds-.25)<1e-9);
 assert.ok(Math.abs(r.laserOffSeconds-.25)<1e-9);
 assert.ok(Math.abs(r.commandedLaserJ-17.5)<1e-8);
 assert.equal(r.scannedLayers,50);
 assert.equal(r.extraOverheadSeconds,null);
 assert.equal(r.illustrativeTotalSeconds,null);
 assert.equal(r.blocked,false);
 assert.match(r.warnings[0],/withheld/);
 assert.equal(r.partSha256,sha(stl));
 const included=calculatePhysicalScanTiming(scan,slices,registration,{...unknown,outsideCsvConfirmed:true});
 assert.ok(Math.abs(included.extraOverheadSeconds!-1900)<1e-9);
 assert.ok(Math.abs(included.illustrativeTotalSeconds!-1900.5)<1e-9);
 assert.equal(included.confidence,"SUPPLIED_UNVERIFIED_COMMANDS");
});
test("blocked geometric registration can still describe supplied data but never establish machine time",async()=>{
 const stl=await f("cube-10mm.stl"),raw=await f("cube-10mm-physical-scan.csv");
 const slices=await slicePhysicalStl(stl,{unitScaleToMm:1,xyPitchMm:1,layerThicknessMm:.2});
 const scan=parsePhysicalScanCsv(new TextDecoder().decode(raw));
 const registration=registerPhysicalScanToSlices({slices,scan,scanSourceSha256:sha(raw)});
 const blocked={...registration,status:"BLOCKED" as const,blockers:["Synthetic blocked geometry"]};
 const r=calculatePhysicalScanTiming(scan,slices,blocked,{outsideCsvConfirmed:false,recoatSecondsPerLayer:0,preparationMinutes:0,cooldownMinutes:0});
 assert.equal(r.blocked,true);
 assert.match(r.warnings[0],/blocked/);
 assert.throws(()=>calculatePhysicalScanTiming(scan,slices,registration,{outsideCsvConfirmed:true,recoatSecondsPerLayer:-1,preparationMinutes:0,cooldownMinutes:0}),/Invalid recoat/);
 assert.throws(()=>calculatePhysicalScanTiming(scan,slices,{...registration,partSha256:"f".repeat(64)},{outsideCsvConfirmed:false,recoatSecondsPerLayer:1,preparationMinutes:0,cooldownMinutes:0}),/Source-identified/);
});
