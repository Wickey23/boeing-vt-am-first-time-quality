import {test,expect} from "@playwright/test";
test("XYZ orientation preview is temporary and keeps analysis controls distinct",async({page})=>{
 await page.setViewportSize({width:1600,height:950});
 await page.goto("/copilot/workbench");
 const ribbon=page.getByRole("region",{name:"CAD analysis commands"});
 const orient=ribbon.getByRole("button",{name:"Orient",exact:true});
 await expect(orient).toBeDisabled();
 await page.getByLabel("Select STL part").setInputFiles("public/verification/cube-10mm.stl");
 await page.getByRole("button",{name:"Confirm units & dimensions"}).click();
 await orient.click();
 const panel=page.getByRole("region",{name:"Orientation preview"});
 await expect(panel).toBeVisible();
 await expect(panel).toContainText("Does not change the selected analysis candidate");
 await panel.getByLabel("X rotation preview").focus();
 await page.keyboard.press("ArrowRight");
 await expect(panel.getByLabel("X rotation preview")).toHaveValue("1");
 await panel.getByLabel("Y rotation preview").focus();
 await page.keyboard.press("ArrowLeft");
 await expect(panel.getByLabel("Y rotation preview")).toHaveValue("-1");
 await expect(ribbon.getByRole("button",{name:"Measure",exact:true})).toBeDisabled();
 await expect(ribbon.getByRole("button",{name:"Section",exact:true})).toBeDisabled();
 await panel.getByRole("button",{name:"Original axes"}).click();
 await expect(panel.getByLabel("X rotation preview")).toHaveValue("0");
 await expect(panel.getByLabel("Y rotation preview")).toHaveValue("0");
 await panel.getByRole("button",{name:"Close orientation preview"}).click();
 await expect(panel).toHaveCount(0);
 await expect(ribbon.getByRole("button",{name:"Measure",exact:true})).toBeEnabled();
 await expect(ribbon.getByRole("button",{name:"Section",exact:true})).toBeEnabled();
});
