import {test,expect} from "@playwright/test";
test("visible engineering interview saves context step-by-step without AI upload",async({page})=>{
 const calls:string[]=[];page.on("request",r=>{if(r.method()==="POST"&&r.url().includes("/api/engineering-copilot"))calls.push(r.url());});
 await page.goto("/copilot");
 await page.getByLabel("Upload target STL").setInputFiles("public/verification/cube-10mm.stl");
 await page.getByRole("button",{name:"Confirm inspected dimensions and units"}).click();
 const field=page.getByLabel("Answer current engineering question");
 const save=page.getByRole("button",{name:"Save answer and continue"});
 await expect(page.getByText("What is this part, and what is its purpose?")).toBeVisible();
 await field.fill("Mounting lug");
 await save.click();
 await expect(page.getByText("Which assembly does it belong to, and what connects to it?")).toBeVisible();
 await field.fill("Public test assembly station 12, source D1");
 await save.click();
 await expect(page.getByText("Where is it fixed, joined or loaded in service?")).toBeVisible();
 await field.fill("End face attachment as an unverified research boundary condition");
 await save.click();
 await expect(page.getByText("Which loads, tolerances and material requirements apply?")).toBeVisible();
 await field.fill("Load magnitude pending engineer confirmation; no certified material allowables");
 await save.click();
 await expect(page.getByRole("button",{name:"Review load and material inputs"})).toBeVisible();
 await page.getByRole("button",{name:"Review load and material inputs"}).click();
 await expect(page.getByLabel("Component role")).toHaveValue("Mounting lug");
 await expect(page.getByLabel("Assembly context")).toHaveValue(/station 12/);
 await expect(page.getByLabel("Reviewed requirements")).toHaveValue(/Load magnitude pending/);
 expect(calls).toEqual([]);
 await page.reload();
 await expect(page.getByRole("button",{name:"Review load and material inputs"})).toBeVisible();
 await page.locator(".copilotFacts > summary").click();
 await expect(page.getByLabel("Component role")).toHaveValue("Mounting lug");
});
