import {test,expect} from "@playwright/test";
test("complete ORIENTAI prebuild workflow links geometry screening, failure scenarios, actions and manufacturing flow",async({page})=>{
 await page.setViewportSize({width:1680,height:900});
 await page.goto("/copilot/workbench");
 await page.getByLabel("Select STL part").setInputFiles("public/verification/cube-10mm.stl");
 await page.getByRole("button",{name:"Confirm units & dimensions"}).click();
 await page.getByRole("region",{name:"Recommended workflow action"}).getByRole("button",{name:"Run screening"}).click();
 await expect(page.getByText(/Geometry screening results · selected orientation/)).toBeVisible({timeout:60000});
 await page.getByRole("navigation",{name:"Assessment stages"}).getByRole("button",{name:/Failure Assessment/}).click();
 await expect(page.getByRole("heading",{name:"Engineering evidence and risks"})).toBeVisible();
 await expect(page.getByRole("button",{name:"Export assessment PDF"})).toBeEnabled();
 const nav=page.getByRole("navigation",{name:"Assessment views"});
 await expect(nav.getByRole("button",{name:"Failure scenarios"})).toHaveAttribute("aria-pressed","true");
 await expect(page.getByText("Lack-of-fusion porosity",{exact:false})).toBeVisible();
 await expect(page.getByText(/not assessed/i).first()).toBeVisible();
 await nav.getByRole("button",{name:"Action plan"}).click();
 await expect(page.getByText("Prioritized engineering actions")).toBeVisible();
 await nav.getByRole("button",{name:"Process flow"}).click();
 await expect(page.getByText("Manufacturing process flow",{exact:true})).toBeVisible();
 await expect(page.getByText("Build preparation and metal printing")).toBeVisible();
 await expect(page.getByText("Inspection and qualification testing")).toBeVisible();
 await nav.getByRole("button",{name:"Assessment coverage"}).click();
 await expect(page.getByText("Supported vs unassessed methods")).toBeVisible();
 await expect(page.getByText("Keyhole pore formation")).toBeVisible();
});
test("LPBF declared process-window violation appears as rule warning, never calibrated defect prediction",async({page})=>{
 await page.goto("/copilot/workbench");
 await page.getByLabel("Select STL part").setInputFiles("public/verification/cube-10mm.stl");
 await page.getByRole("button",{name:"Confirm units & dimensions"}).click();
 await page.getByRole("navigation",{name:"Assessment stages"}).getByRole("button",{name:/Engineering Context/}).click();
 const panel=page.getByRole("article",{name:"LPBF process-window review"});
 await panel.locator("summary").first().click();
 await panel.getByRole("textbox",{name:"Machine / build system"}).fill("Research machine R");
 await panel.getByRole("textbox",{name:"Alloy and condition"}).fill("Ti64 test material");
 await panel.getByRole("textbox",{name:"Parameter set ID"}).fill("P-1");
 await panel.getByRole("textbox",{name:"Source and revision"}).fill("Machine process trial rev 1");
 await panel.getByRole("spinbutton",{name:"Planned Laser power"}).fill("500");
 await panel.getByRole("spinbutton",{name:"Laser power minimum"}).fill("100");
 await panel.getByRole("spinbutton",{name:"Laser power maximum"}).fill("300");
 await expect(panel.getByText(/Outside supplied boundaries/)).toBeVisible();
 await page.getByRole("navigation",{name:"Assessment stages"}).getByRole("button",{name:/Failure Assessment/}).click();
 await expect(page.getByText("Parameter outside declared process range")).toBeVisible();
 await expect(page.getByText(/does not establish defect likelihood/i)).toHaveCount(0);
 await expect(page.getByText(/Physical defect prediction remains unvalidated/)).toBeVisible();
});
test("post-build inspection records are source-traceable and retained for the same STL",async({page})=>{
 await page.goto("/copilot/workbench");
 await page.getByLabel("Select STL part").setInputFiles("public/verification/cube-10mm.stl");
 await page.getByRole("navigation",{name:"Assessment stages"}).getByRole("button",{name:/Failure Assessment/}).click();
 await page.getByRole("navigation",{name:"Assessment views"}).getByRole("button",{name:"Process flow"}).click();
 const panel=page.getByRole("region",{name:"Post-build inspection feedback"});
 await panel.locator("summary").last().click();
 await panel.getByRole("textbox",{name:"Build / specimen ID"}).fill("RESEARCH-BUILD-42");
 await panel.getByRole("textbox",{name:"Report / source revision"}).fill("TEST-42 Rev A");
 await panel.getByRole("textbox",{name:"Test or inspection method"}).fill("Optical measured dimensions");
 await panel.getByRole("textbox",{name:"Engineer / reviewer"}).fill("Engineer-1");
 await panel.getByRole("textbox",{name:"Observed result and test conditions"}).fill("Measured corner dimensions under laboratory test conditions. Source reviewed by operator.");
 await panel.getByRole("checkbox",{name:/I reviewed the cited source/}).check();
 await panel.getByRole("button",{name:"Add reviewed observation"}).click();
 await expect(panel.getByText("RESEARCH-BUILD-42",{exact:false})).toBeVisible();
 await page.getByRole("navigation",{name:"Assessment stages"}).getByRole("button",{name:/Part Geometry/}).click();
 await page.getByRole("navigation",{name:"Assessment stages"}).getByRole("button",{name:/Failure Assessment/}).click();
 await page.getByRole("navigation",{name:"Assessment views"}).getByRole("button",{name:"Process flow"}).click();
 await expect(page.getByText("RESEARCH-BUILD-42",{exact:false})).toBeVisible();
});
