import {test,expect} from "@playwright/test";
test("new user completes one STL project without switching to unrelated geometry",async({page})=>{
 const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto("/orientation");
 await expect(page.getByRole("heading",{name:"What component are we analyzing?"})).toBeVisible();
 await page.getByLabel("Upload STL").setInputFiles("public/verification/cube-10mm.stl");
 await expect(page.getByText(/10.00 × 10.00 × 10.00/)).toBeVisible();
 await page.getByRole("button",{name:"Confirm units and continue"}).click();
 await expect(page.getByRole("heading",{name:"What does this part need to withstand?"})).toBeVisible();
 await expect(page.getByLabel("Force Z (N)")).toHaveValue("100");
 await page.getByLabel("Force X (N)").fill("15");
 await page.getByRole("button",{name:/Continue: Print process/}).click();
 await expect(page.getByLabel("Manufacturing process")).toHaveValue("PBF_LB_METAL");
 await page.getByRole("button",{name:/Continue: Options/}).click();
 await page.getByRole("button",{name:"Generate orientation candidates"}).click();
 await expect(page.getByText("96 sampled orientations")).toBeVisible();
 await page.getByRole("button",{name:/Continue: Simulations/}).click();
 await expect(page.getByText("Service-load response")).toBeVisible();
 await page.getByRole("button",{name:/Continue: Decision/}).click();
 await expect(page.getByText("Not a print approval.")).toBeVisible();
 await page.getByRole("button",{name:/Continue: Report/}).click();
 await expect(page.getByRole("link",{name:/Open engineering PDF/})).toBeVisible();
 const pending=page.waitForEvent("download");
 await page.getByRole("button",{name:"Export complete project backup"}).click();
 const data=JSON.parse(await (await import("node:fs/promises")).readFile((await (await pending).path())!,"utf8"));
 expect(data.journey.schema).toBe(2);
 expect(data.journey.process).toBe("PBF_LB_METAL");
 expect(data.servicePlan.cases[0].input.forceXN).toBe(15);
 await page.reload();
 await expect(page.getByRole("heading",{name:"Export what we know—and what we do not."})).toBeVisible();
 expect(errors).toEqual([]);
});
test("DED teaching project is explicitly synthetic, shows supported stages and exports separately",async({page})=>{
 await page.goto("/");
 await page.locator(".oaAdvanced > summary").click();
 await page.getByRole("link",{name:/Launch DED example/}).click();
 await expect(page.getByRole("heading",{name:"DED research example"})).toBeVisible();
 await expect(page.getByText("Synthetic DED teaching wall").first()).toBeVisible();
 await page.getByRole("button",{name:/Continue: Requirements/}).click();
 await expect(page.getByText(/not a flight-design mechanical component/)).toBeVisible();
 await page.getByRole("button",{name:/Continue: Print process/}).click();
 await expect(page.getByLabel("DED variant")).toHaveValue("DED_LB_WIRE");
 await page.getByRole("button",{name:/Continue: Options/}).click();
 await expect(page.getByLabel("Deposition strategy")).toHaveValue("alternating");
 await expect(page.getByText("480 mm").first()).toBeVisible();
 await page.getByRole("button",{name:/Continue: Simulations/}).click();
 await expect(page.getByText(/Mean lead time/)).toBeVisible();
 const pending=page.waitForEvent("download");
 await page.getByRole("button",{name:"Export Simio CSV tables (ZIP)"}).click();
 expect((await pending).suggestedFilename()).toMatch(/^ded-wall-.*-simio-data.zip$/);
 await page.getByRole("button",{name:/Continue: Decision/}).click();
 await expect(page.getByText("Print feasibility and quality not established")).toBeVisible();
 await page.getByRole("button",{name:/Continue: Report/}).click();
 const exportJson=page.waitForEvent("download");
 await page.getByRole("button",{name:"Download DED research review (JSON)"}).click();
 const report=JSON.parse(await (await import("node:fs/promises")).readFile((await (await exportJson).path())!,"utf8"));
 expect(report.source).toBe("synthetic-ded-wall");
 expect(report.machineFeasibility).toBe("not_evaluated");
 await page.reload();
 await expect(page.getByRole("heading",{name:"Export what we know—and what we do not."})).toBeVisible();
});
test("uploaded STL plus a DED process cannot silently use LPBF candidate results",async({page})=>{
 await page.goto("/orientation");
 await page.getByLabel("Upload STL").setInputFiles("public/verification/cube-10mm.stl");
 await page.getByRole("button",{name:"Confirm units and continue"}).click();
 await page.getByRole("button",{name:/Continue: Print process/}).click();
 await page.getByLabel("Manufacturing process").selectOption("DED_LB_WIRE");
 await expect(page.getByText(/not supported for arbitrary STL files/)).toBeVisible();
 await page.getByRole("button",{name:/Continue: Options/}).click();
 await expect(page.getByText(/No validated toolpath engine for your uploaded STL/)).toBeVisible();
 await page.getByRole("button",{name:/Continue: Simulations/}).click();
 await expect(page.getByText(/No DED simulation is available for this arbitrary uploaded STL/)).toBeVisible();
 await page.getByRole("button",{name:/Continue: Decision/}).click();
 await expect(page.getByText(/No process-specific decision is available/)).toBeVisible();
});
